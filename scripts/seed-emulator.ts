const daysAgo = (n: number): Timestamp => Timestamp.fromMillis(Date.now() - n * 86_400_000);
const dateStr = (n: number): string => new Date(Date.now() - n * 86_400_000).toISOString().slice(0, 10);

function requireEmulators(): void {
  const missing = ["FIRESTORE_EMULATOR_HOST", "FIREBASE_AUTH_EMULATOR_HOST"].filter((k) => !process.env[k]);
  if (missing.length > 0) {
    throw new Error(`Refusing to run: ${missing.join(" and ")} not set. Start the emulators and use npm run seed:emulator.`);
  }
}

async function createUsers(): Promise<Map<string, string>> {
  const auth = getAuth();
  const db = getFirestore();
  const uids = new Map<string, string>();
  const envLines: string[] = ["# Generated by npm run seed:emulator. Emulator-only test accounts."];
  for (const user of USERS) {
    const password = randomBytes(12).toString("base64url");
    const props = { email: user.email, password, displayName: user.displayName, emailVerified: true };
    let uid: string;
    try {
      uid = (await auth.getUserByEmail(user.email)).uid;
      await auth.updateUser(uid, props);
    } catch (err) {
      if ((err as { code?: string }).code !== "auth/user-not-found") throw err;
      uid = (await auth.createUser(props)).uid;
    }
    await auth.setCustomUserClaims(uid, user.role);
    await db.doc(`roles/${user.email.toLowerCase()}`).set(user.role);
    await db.doc(`users/${uid}`).set(
      {
        isAnonymous: false,
        email: user.email,
        displayName: user.displayName,
        photoURL: null,
        consent: "granted",
        country: "GB",
        createdAt: daysAgo(30),
        lastSeenAt: daysAgo(0),
      },
      { merge: true },
    );
    uids.set(user.key, uid);
    envLines.push(`EMULATOR_${user.key}_EMAIL=${user.email}`, `EMULATOR_${user.key}_PASSWORD=${password}`);
  }
  writeFileSync(ENV_FILE, `${envLines.join("\n")}\n`, { mode: 0o600 });
  return uids;
}

