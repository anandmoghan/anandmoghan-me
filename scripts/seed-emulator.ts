const kebab = (s: string): string => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

async function seedLadder(db: Firestore): Promise<void> {
  for (const t of TRACKERS) {
    const root = db.doc(`ladder/${t.tracker}`);
    await root.set({ tracker: t.tracker });
    let i = 0;
    for (const [status, company, role] of t.jobs) {
      const discovered = dateStr(3 + i * 4);
      const slug = `${discovered}-${kebab(company)}-${kebab(role)}`;
      const job: Row = {
        tracker: t.tracker,
        slug,
        title: role,
        company,
        url: `https://example.com/jobs/${slug}`,
        status,
        discovered_date: discovered,
        viewed: status !== "new",
        location: t.region === "uk" ? "London, UK" : "Zurich, Switzerland",
        remote: "hybrid",
        region: t.region,
        hiring_scope: t.scope,
        hiring_scope_confidence: "inferred",
        sponsorship: "unknown",
        pay_min: 70000,
        pay_max: 95000,
        pay_currency: t.currency,
        pay_period: "year",
        pay_confidence: "inferred",
        tags: ["fake", status],
        fit_summary: "Fake job posting for local testing.",
        body_html: `<p>${role} at ${company}. This is fake seed data.</p>`,
        created_at: daysAgo(3 + i * 4),
        updated_at: daysAgo(1),
      };
      if (status === "applied" || status === "interviewing" || status === "declined") {
        job.applied_date = dateStr(2 + i * 3);
        job.progress_stage = status === "interviewing" ? "phone_screen" : status === "declined" ? "declined" : "applied";
      }
      if (status === "declined") job.decision_date = dateStr(1);
      if (status === "interviewing") job.notes = [{ date: dateStr(1), text: "Recruiter call booked." }];
      await root.collection("jobs").doc(slug).set(job);
      i += 1;
    }
    for (const [slug, name] of t.companies) {
      await root.collection("companies").doc(slug).set({
        slug,
        name,
        career_page_url: `https://example.com/${slug}/careers`,
        ats: "greenhouse",
        tags: ["fake"],
        regions: [t.region],
        last_verified_date: dateStr(7),
        notes: "Fake company for local testing.",
        sponsorship: "unknown",
        sponsorship_confidence: "unknown",
        body_html: `<p>${name}: fake seed data.</p>`,
        created_at: daysAgo(10),
        updated_at: daysAgo(7),
      });
    }
    const first = t.jobs[0];
    const firstSlug = `${dateStr(3)}-${kebab(first[1])}-${kebab(first[2])}`;
    await root.collection("requests").doc().set({
      type: "refresh-job",
      status: "queued",
      slug: firstSlug,
      createdBy: "admin@test.local",
      createdAt: daysAgo(0),
    });
  }
}

