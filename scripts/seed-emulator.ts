//
//   npm run emulators          (in one terminal)
//   npm run seed:emulator      (in another)
//
// Refuses to run unless both emulator hosts are set, so it can never touch the live project. The
// `seed:emulator` npm script sets them. Test passwords are random per run and written to the
// gitignored .env.emulator.local (never printed). Everything here is fake data.

